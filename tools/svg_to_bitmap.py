"""Render an SVG to a C++ header holding the image as a palette (indexed) bitmap.

Usage:
    python tools/svg_to_bitmap.py <input.svg> <output.h> <Name> [--bits {1,2,4,8}]

The image is reduced to at most 2^bits colours (default 4 bits: 16 colours),
and each pixel is stored as an index into that colour table. That's a quarter
of the size of full 16-bit colour at 4 bits, which is plenty for icons: a few
flat colours plus the smoothed shades along their edges. The script prints
how far the reduced image deviates from the full-colour render, so you can
see whether a different --bits is worth it.

The header defines namespace <Name> with:
  WIDTH, HEIGHT  image size in pixels
  DEPTH          the LovyanGFX palette depth (lgfx::palette_<bits>bit)
  PALETTE        the colour table, std::array<lgfx::rgb565_t, 2^bits>
  PIXELS         the indices, std::array<uint8_t, ...>, packed in the layout
                 LovyanGFX's palette pushImage() reads: row-major, first pixel
                 in the most significant bits, no padding between rows
  draw(tft, x, y)  draws it with its top-left corner at (x, y)
All data is constexpr, so it lives in flash, not RAM.

The SVG is rendered at its own size (1 SVG unit = 1 screen pixel) on a black
background, the screen background, so smoothed edges blend into black.

Requires: pip install -r tools/requirements.txt
"""

import argparse
import io
from pathlib import Path

import resvg_py
from PIL import Image

BYTES_PER_LINE = 16


def rgb565(r: int, g: int, b: int) -> int:
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def rgb565_to_rgb(value: int) -> tuple[int, int, int]:
    return ((value >> 11) << 3, ((value >> 5) & 0x3F) << 2, (value & 0x1F) << 3)


def pack(indices: list[int], bits: int) -> list[int]:
    """Packs indices MSB-first into bytes, continuously across rows."""
    packed = []
    current = 0
    filled = 0
    for index in indices:
        current = (current << bits) | index
        filled += bits
        if filled == 8:
            packed.append(current)
            current = 0
            filled = 0
    if filled:
        packed.append(current << (8 - filled))
    return packed


def format_values(values: list[str], per_line: int) -> str:
    lines = []
    for start in range(0, len(values), per_line):
        lines.append("    " + ", ".join(values[start : start + per_line]) + ",")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("svg", type=Path)
    parser.add_argument("header", type=Path)
    parser.add_argument("name", help="C++ namespace for the generated constants and draw()")
    parser.add_argument("--bits", type=int, choices=(1, 2, 4, 8), default=4, help="bits per pixel (default 4)")
    args = parser.parse_args()

    png = bytes(resvg_py.svg_to_bytes(svg_path=str(args.svg), background="#000000"))
    image = Image.open(io.BytesIO(png)).convert("RGB")
    width, height = image.size

    colours = 1 << args.bits
    reduced = image.quantize(colors=colours, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    indices = list(reduced.tobytes())
    flat_palette = reduced.getpalette() or []
    palette = [rgb565(*flat_palette[i * 3 : i * 3 + 3]) for i in range(len(flat_palette) // 3)][:colours]
    palette += [0x0000] * (colours - len(palette))  # unused entries: black

    # How far the reduced image is from the full-colour one, both in RGB565.
    raw = image.tobytes()
    errors = []
    for i, index in enumerate(indices):
        full = rgb565_to_rgb(rgb565(raw[3 * i], raw[3 * i + 1], raw[3 * i + 2]))
        approx = rgb565_to_rgb(palette[index])
        errors.append(max(abs(a - b) for a, b in zip(full, approx)))

    packed = pack(indices, args.bits)

    svg_display = args.svg.as_posix()
    command = f"python tools/svg_to_bitmap.py {svg_display} {args.header.as_posix()} {args.name}"
    if args.bits != 4:
        command += f" --bits {args.bits}"
    palette_values = format_values([f"0x{value:04X}" for value in palette], 8)
    pixel_values = format_values([f"0x{value:02X}" for value in packed], BYTES_PER_LINE)

    header = f"""#pragma once

// GENERATED by tools/svg_to_bitmap.py from {svg_display} - do not edit.
// Edit the SVG and regenerate:
//   {command}

#include <array>
#include <stdint.h>

#include <LovyanGFX.hpp>

namespace {args.name} {{

inline constexpr int32_t WIDTH = {width};
inline constexpr int32_t HEIGHT = {height};

// {colours}-colour palette image: each pixel is a {args.bits}-bit index into PALETTE.
inline constexpr lgfx::color_depth_t DEPTH = lgfx::palette_{args.bits}bit;

inline constexpr std::array<lgfx::rgb565_t, {colours}> PALETTE{{{{
{palette_values}
}}}};

// Row-major, first pixel in the most significant bits, no padding between rows.
inline constexpr std::array<uint8_t, {len(packed)}> PIXELS{{{{
{pixel_values}
}}}};

// Draws the image with its top-left corner at (x, y).
inline void draw(LGFX &tft, int32_t x, int32_t y) {{
  tft.pushImage(x, y, WIDTH, HEIGHT, PIXELS.data(), DEPTH, PALETTE.data());
}}

}} // namespace {args.name}
"""
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(header, encoding="utf-8", newline="\n")

    data_bytes = len(packed) + 2 * len(palette)
    print(f"{args.header}: {width}x{height}, {colours} colours, {data_bytes} bytes "
          f"(full 16-bit colour would be {2 * width * height})")
    print(f"colour reduction: max channel error {max(errors)}, "
          f"{sum(e > 24 for e in errors)} of {len(errors)} pixels off by more than 24")


if __name__ == "__main__":
    main()
